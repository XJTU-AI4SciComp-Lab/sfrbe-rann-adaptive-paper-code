function cfg = config()
%CONFIG  Two-peak Poisson AD+SFR only variant (no RBE).
%
%   Same problem and hyperparameters as the full pipeline, except:
%     - run_rbe = false          -> stop after SFR (AD + SFR only)
%     - model.neuron = 6530      -> DOF matches the average DOF (6530) of the
%                                   full AD+SFR+RBE runs
%     - seed = 0:9               -> main runs seeds 0..9, each saved to
%                                   results/poisson_2peak_sfr_seed<k>/

    root = fileparts(fileparts(fileparts(mfilename('fullpath')))); % project root

    cfg.problem = 'poisson_2peak';
    cfg.paper.table  = 'tab02_poisson2peak_sfr';
    cfg.paper.figures = { ...
        'fig06_poisson2peak_exact_sol', ...
        'fig06_poisson2peak_num_sol', ...
        'fig06_poisson2peak_sfr_anchor', ...
        'fig07_poisson2peak_ini_error', ...
        'fig07_poisson2peak_sfr_error'};

    % ---------------- randomness ----------------
    cfg.seed = 0:9;              % run seeds 0..9
    cfg.rng_reset_each_stage = true;

    % ---------------- pipeline ----------------
    cfg.run_rbe = false;         % AD + SFR only, no RBE

    % ---------------- grid / boundary ----------------
    cfg.grid.N        = [150, 150]; % N_pde = 22500
    cfg.grid.b_point  = 200;        % N_b = 800

    % ---------------- model ----------------
    cfg.model.family     = 'tanh';
    cfg.model.neuron     = 6450;   % DOF = mean final DOF over Poisson seeds 0:9
    cfg.model.neuron_add = 1000;   % unused when run_rbe=false
    cfg.model.r0         = [15; 15];
    cfg.model.eta0       = 100000;

    % ---------------- solver ----------------
    cfg.solver.GPU = 0;
    cfg.solver.QR  = 1;
    cfg.solver.orth_rel_tol = 1e-10;

    % ---------------- PDAD initial scale training ----------------
    cfg.pdad.n_pde_rtrain    = 3000;
    cfg.pdad.n_bd_rtrain     = 600;
    cfg.pdad.n_neuron_rtrain = 800;
    cfg.pdad.opts = struct( ...
        'family',        'tanh', ...
        'maxit',         40, ...
        'learning_rate', 0.5, ...
        'eta_bc_train',  5.0, ...
        'lambda_ridge',  1e-6, ...
        'clip_min',      [1; 1], ...
        'clip_max',      [500; 500], ...
        'normalize_grad', true, ...
        'verbose',       false, ...
        'print_every',   10);

    % ---------------- SFR ----------------
    cfg.sfr.cfg = struct( ...
        'diag_N', [200, 200], 'partition_grid', [1, 1], 'SAB_eps', 1e-12, ... % one global SFR region
        'theta_dorfler', 0.50, 'theta_res', 0.5, 'theta_grad', 0.5, 'delta_floor', 1.0e-3, ...
        'tau_eff', 0.35, ...     % paper Table 12
        'tau_conn', 0.01, ...     % normalized score-mass floor for components
        'tau_cover', 0.35, ...   % paper Table 12
        'use_cover_gate_for_refresh', true, ...
        'plot_figures', false);
    cfg.sfr.ref = struct( ...
        'gamma_AD', 1.0, 'max_train_points_S', [], 'max_train_points_B', [], ...
        'lambda_reg', 1e-6, ...
        'eta_accept', 0.0, 'eta_val', cfg.model.eta0, ...
        'val_N', [100, 100], 'b_val', 600, ...
        'use_center_jitter', true, 'kappa_jit', 1.0, ... % uniform sampling in selected diagnostic cells
        'plot_figures', false, ...
        'adam_opts', struct('eta', 0.7, 'maxit', 30, ...
                            'eps_adam', 1e-8));

    % ---------------- RBE (kept for reference; disabled by run_rbe=false) ----------------
    cfg.rbe = struct( ...
        'stage_name', 'ScoreFamily', ...
        'families', {{'tanh','ridge_gauss','sin','radial_gauss','mexican_hat'}}, ...
        'family_repeat_mode', 'exclude_last', ...
        'max_family_rounds', 8, ...
        'screen_ratio', 0.30, 'screen_max', 500, ...
        'neuron_add', cfg.model.neuron_add, ...
        'm_block0', cfg.model.neuron_add, ...
        'm_block_min', 200, 'm_block_max', cfg.model.neuron_add, ...
        'm_frac_list', [0.2, 0.4, 0.5, 0.6, 0.7, 0.8, 0.9, 1.0], ...
        'prefix_score_ratio', 0.80, ...
        'tau_stop_score', 0.25, ...
        'lambda', 1e-6, ...
        'delta', 3.0e-3, 'q', 2, 'rho', 0.85, ...
        'tau_cap', 1e-4, 'eta_accept', 0.0, ...
        'kappa_map_max', 1e6, ...
        'tol_res', 1e-6, ...
        'tol_improve', 0.1, 'stall_patience', 2, ...
        'stop_when_reject', false, 'rollback_worse_tol', 0.05, ...
        'gamma_AD', 1.0, 'max_train_points', [], ...
        'plot_figures', false, ...
        'screen_adam_opts', struct('eta', 0.5, 'maxit', 30, ...
            'eps_adam', 1e-8, 'clip_min', [1; 1], 'clip_max', [500; 500], ...
            'minit', 5, 'grad_tol', 1e-12, 'fd_step_rel', 1e-4, ...
            'verbose', false, 'use_rel_grad', false));

    % ---------------- output ----------------
    cfg.output.results_root = fullfile(root, 'results');
    cfg.output.figures_root = fullfile(root, 'figures');
    cfg.output.run_tag_base = 'poisson_2peak_sfr';  % results/poisson_2peak_sfr_seed<k>/
    cfg.output.run_name = '';
    cfg.output.save_data    = true;
    cfg.output.make_figs    = false;   % plot later with plotFromResults
    cfg.output.pp           = 100;
    cfg.output.val_N        = [100, 100];
end
