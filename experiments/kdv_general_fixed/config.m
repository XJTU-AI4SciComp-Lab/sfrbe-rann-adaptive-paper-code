function cfg = config()
%CONFIG  Generalized KdV experiment (paper Section 6.3 Case 1).
%
%   PDE: u_t + u_x + u^3 u_x + eps u_xxx = 0, (x,t) in (-2,3) x (0,2),
%   eps = 0.2058e-4.
%   Fixed-operator run: initial tanh 2000, SFR 998 structure + 1002 background,
%   and five RBE blocks adding 1800 features (3800 total).
%   Paper discretization: N_pde=22500, N_b=400, N_0=200, m_full=1000.
    root = fileparts(fileparts(fileparts(mfilename('fullpath')))); % project root

    cfg.problem = 'kdv_general';
    cfg.paper.table  = 'tab06_kdv_fixed_operator';
    cfg.paper.figures = { ...
        'fig12_kdv_exact_sol', ...
        'fig12_kdv_num_sol', ...
        'fig12_kdv_sfr_anchor', ...
        'fig13_kdv_ini_error', ...
        'fig13_kdv_sfr_error', ...
        'fig13_kdv_rbe_error'};
    cfg.paper.fig_file = struct( ...
        'exact_sol', 'KDV_exact_sol', ...
        'num_sol',   'KDV_num_sol', ...
        'sfr_anchor','KDV_SFR_anchor', ...
        'ini_error', 'KDV_INI_error', ...
        'sfr_error', 'KDV_SFR_error', ...
        'rbe_error', 'KDV_RBE_error');

    % ---------------- randomness ----------------
    cfg.seed = 4;
    cfg.rng_reset_each_stage = true;
    cfg.run_pdad = false;      % nonlinear KdV: skip the Poisson-type PDAD scale warm-up

    % ---------------- nonlinear solve ----------------
    cfg.run_newton = false;                % fixed-operator run
    cfg.run_newton_initial = false;
    cfg.run_newton_sfr = false;
    cfg.run_ddad_after_newton = true;      % value-fit -> fixed operator -> DDAD(r) -> rebuild -> fixed operator
    cfg.newton_ddad = struct('num_newton', 1, 'eta_bc', 100, 'tau_newton', 1e-8, 'verbose', false, 'line_search', true, 'max_line_search', 8, 'tol_newton_improve', 1e-4, 'stall_patience', 2, 'min_newton_iter', 2, 'linear_solver', 'svd', 'svd_mode', 'none', 'svd_rel_tol', 1e-10, 'svd_fixed_rank', 1200, 'solve_lambda', 0);
    cfg.ddad_opts = struct('maxit', 30, 'eta', 0.5, 'eps_adam', 1e-8, ...
        'clip_min', [1; 1], 'clip_max', [500; 500], ...
        'minit', 5, 'grad_tol', 1e-12, 'fd_step_rel', 1e-4, ...
        'verbose', false, 'use_rel_grad', false);
    cfg.newton = struct('num_newton', 4, 'eta_bc', 100, 'tau_newton', 1e-8, 'verbose', false, 'line_search', true, 'max_line_search', 8, 'tol_newton_improve', 1e-4, 'stall_patience', 2, 'min_newton_iter', 2, 'linear_solver', 'svd', 'svd_mode', 'none', 'svd_rel_tol', 1e-10, 'svd_fixed_rank', 1200, 'solve_lambda', 0);   % legacy KdV eta_bc = 100

    % ---------------- grid / boundary (paper Table 11) ----------------
    cfg.grid.N        = [150, 150];  % N_pde = 22500 (x,t)
    cfg.grid.b_point  = 200;         % used for fallback only (problem provides x_0)

    % ---------------- model ----------------
    cfg.model.family     = 'tanh';
    cfg.model.neuron     = 2000;     % initial features (paper Table 6)
    cfg.model.neuron_add = 1000;     % RBE m_full (paper Table 11)
    cfg.model.r0         = [10; 10];
    cfg.model.eta0       = 100;

    % ---------------- solver ----------------
    cfg.solver.GPU = 0;
    cfg.solver.QR  = 1;
    cfg.solver.orth_rel_tol = 1e-10;

    % ---------------- PDAD initial scale training ----------------
    cfg.pdad.n_pde_rtrain    = 3000;
    cfg.pdad.n_bd_rtrain     = 600;
    cfg.pdad.n_neuron_rtrain = 800;
    cfg.pdad.opts = struct( ...
        'family',        'tanh', ...
        'maxit',         40, ...
        'learning_rate', 0.5, ...
        'eta_bc_train',  5.0, ...
        'lambda_ridge',  1e-6, ...
        'clip_min',      [1; 1], ...
        'clip_max',      [500; 500], ...
        'normalize_grad', true, ...
        'verbose',       false, ...
        'print_every',   10);

    % ---------------- SFR (paper Table 12 defaults) ----------------
    cfg.sfr.cfg = struct( ...
        'diag_N', [200, 200], 'partition_grid', [1, 1], 'SAB_eps', 1e-12, ... % one global SFR region
        'theta_dorfler', 0.50, 'theta_res', 0.5, 'theta_grad', 0.5, 'delta_floor', 1.0e-3, ...
        'tau_eff', 0.35, ...
        'tau_conn', 0.01, ...     % normalized score-mass floor for components
        'tau_cover', 0.35, ...
        'use_cover_gate_for_refresh', true, ...
        'plot_figures', false);
    cfg.sfr.ref = struct( ...
        'gamma_AD', 1.0, 'max_train_points_S', [], 'max_train_points_B', [], ...
        'lambda_reg', 1e-6, ...
        'eta_accept', 0.0, 'eta_val', cfg.model.eta0, ...
        'val_N', [100, 100], 'b_val', 600, ...
        'newton_refine', false, 'newton', cfg.newton, ...  % fixed-operator SFR refresh
        'use_center_jitter', true, 'kappa_jit', 1.0, ... % uniform sampling in selected diagnostic cells
        'plot_figures', false, ...
        'adam_opts', struct('eta', 0.7, 'maxit', 30, ...
                            'eps_adam', 1e-8));

    % ---------------- RBE (families limited to those supporting u_xxx) ----------------
    cfg.rbe = struct( ...
        'stage_name', 'ScoreFamily', ...
        'families', {{'tanh','ridge_gauss','sin'}}, ...
        'family_repeat_mode', 'exclude_last', ...
        'max_family_rounds', 5, ...
        'screen_ratio', 0.30, 'screen_max', 500, ...
        'neuron_add', cfg.model.neuron_add, ...
        'm_block0', cfg.model.neuron_add, ...
        'm_block_min', 200, 'm_block_max', cfg.model.neuron_add, ...
        'm_frac_list', [0.2, 0.4, 0.5, 0.6, 0.7, 0.8, 0.9, 1.0], ...
        'prefix_score_ratio', 0.80, ...
        'tau_stop_score', 0.25, ...
        'lambda', 1e-6, ...
        'delta', 3.0e-3, 'q', 2, 'rho', 0.85, ...
        'tau_cap', 1e-4, 'eta_accept', 0.0, ...
        'kappa_map_max', 1e6, ...
        'tol_res', 1e-6, ...
        'tol_improve', 0.1, 'stall_patience', 2, ...
        'stop_when_reject', true, 'rollback_worse_tol', 0.05, ...
        'gamma_AD', 1.0, 'max_train_points', [], ...
        'incremental_init', true, ...
        'plot_figures', false, ...
        'run_newton_each_block', false, ...  % fixed-operator incremental RBE update
        'newton', cfg.newton, ...
        'use_frozen_jacobian', true, ...   % frozen Newton-Jacobian scoring for nonlinear RBE
        'screen_adam_opts', struct('eta', 0.5, 'maxit', 30, ...
            'eps_adam', 1e-8, 'clip_min', [1; 1], 'clip_max', [300; 300], ...
            'minit', 5, 'grad_tol', 0, 'fd_step_rel', 1e-4, ...
            'verbose', false, 'use_rel_grad', true));   % relative-gradient Adam (legacy kdv_residual)

    % ---------------- output ----------------
    cfg.output.results_root = fullfile(root, 'results');
    cfg.output.figures_root = fullfile(root, 'figures');
    cfg.output.run_tag_base = 'kdv_general_fixed';
    cfg.output.run_name = '';
    cfg.output.save_data    = true;
    cfg.output.make_figs    = true;
    cfg.output.pp           = 150;
    cfg.output.val_N        = [100, 100];

    % ================================================================
    % Fixed-operator Picard variant.  All settings remain explicit here,
    % so this file contains the only reported generalized-KdV experiment.
    % The original Newton experiment is preserved in its own directory.
    cfg.paper.table = 'tab06_kdv_fixed_operator';
    cfg.output.run_tag_base = 'kdv_general_fixed';
    cfg.run_newton = false;
    cfg.run_newton_initial = false;
    cfg.run_newton_sfr = false;
    cfg.run_ddad_after_newton = true;
    cfg.sfr.ref.newton_refine = false;
    cfg.rbe.run_newton_each_block = false;
    cfg.fixed_operator = struct( ...
        'enabled', true, ...
        'sigma', 0, ...
        'omega', 0.7, ...
        'omega_min', 1e-3, ...
        'maxit', 25, ...
        'max_line_search', 10, ...
        'tol', 1e-7, ...
        'accept_increase', 0.0, ...
        'initial_value_fit', true, ...
        'ddad_max_outer', 1, ...
        'eta_bc', cfg.model.eta0, ...
        'verbose', false);
end
