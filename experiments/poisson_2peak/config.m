function cfg = config()
%CONFIG  Two-peak Poisson experiment configuration.
%
%   Defaults reproduce the PAPER script exactly:
%   SFR/RBE configuration for the two-peak Poisson experiment.
%   (NOT main_score.m, which uses N=[200,200] and other differences).
%
%   Expected paper numbers (Table 2, measured on pp=100 grid):
%     initial rel L2 ~ 3.7e-2 -> SFR ~ 8.4e-4 -> RBE final ~ 1.9e-7.

    root = fileparts(fileparts(fileparts(mfilename('fullpath')))); % project root

    cfg.problem = 'poisson_2peak';
    cfg.paper.table  = 'tab02_poisson2peak';
    cfg.paper.figures = { ...
        'fig06_poisson2peak_exact_sol', ...
        'fig06_poisson2peak_num_sol', ...
        'fig06_poisson2peak_sfr_anchor', ...
        'fig07_poisson2peak_ini_error', ...
        'fig07_poisson2peak_sfr_error', ...
        'fig07_poisson2peak_rbe_error'};
    % output file names follow the paper (no figNN_ prefix)
    cfg.paper.fig_file = struct( ...
        'exact_sol',  'possion_gauss_exact_sol', ...
        'num_sol',    'possion_gauss_num_sol', ...
        'sfr_anchor', 'possion_gauss_SFR_anchor', ...
        'ini_error',  'possion_gauss_INI_error', ...
        'sfr_error',  'possion_gauss_SFR_error', ...
        'rbe_error',  'possion_gauss_RBE_error');

    % ---------------- randomness ----------------
    % One field: cfg.seed. Scalar = run once; vector = main runs once per seed,
    % each stored in results/<problem>_seed<k>/.
    cfg.seed = 0:9;
    % true -> reset rng(cfg.seed) before SFR and RBE (fully reproducible).
    % false -> keep the continuing random stream (paper-legacy behavior).
    cfg.rng_reset_each_stage = true;

    % ---------------- grid / boundary (paper script: N=[150,150]) ----------------
    cfg.grid.N        = [150, 150]; % N_pde = 22500 (paper Table 11)
    cfg.grid.b_point  = 200;        % N_b = 800 (paper Table 11)

    % ---------------- model ----------------
    cfg.model.family     = 'tanh';
    cfg.model.neuron     = 3500;    % initial feature count (paper Tables 2 / 11)
    cfg.model.neuron_add = 1000;    % RBE candidate block m_full per round (paper Table 11)
    cfg.model.r0         = [15; 15];% initial distribution scale (PDAD start)
    cfg.model.eta0       = 100000;  % boundary/initial constraint weight (final solve)

    % ---------------- solver ----------------
    cfg.solver.GPU = 0;
    cfg.solver.QR  = 1;
    cfg.solver.orth_rel_tol = 1e-10;  % SVD truncation for residual-orthogonal basis
                                      % (paper tau_svd, Table 12); set 0 to disable

    % ---------------- PDAD initial scale training (paper script values) ----------------
    cfg.pdad.n_pde_rtrain    = 3000; % interior point count for r training
    cfg.pdad.n_bd_rtrain     = 600;  % boundary point count for r training
    cfg.pdad.n_neuron_rtrain = 800;  % feature count for r training
    cfg.pdad.opts = struct( ...
        'family',        'tanh', ...
        'maxit',         40, ...
        'learning_rate', 0.5, ...
        'eta_bc_train',  5.0, ...
        'lambda_ridge',  1e-6, ...
        'clip_min',      [1; 1], ...
        'clip_max',      [500; 500], ...
        'normalize_grad', true, ...
        'verbose',       false, ...
        'print_every',   10);

    % ---------------- SFR (global residual--solution-gradient marking) ----------------
    cfg.sfr.cfg = struct( ...
        'diag_N', [200, 200], 'partition_grid', [1, 1], 'SAB_eps', 1e-12, ... % one global SFR region
        'theta_dorfler', 0.50, 'theta_res', 0.5, 'theta_grad', 0.5, ... % residual/solution-gradient blend
        'delta_floor', 1.0e-3, ...                              % measure-consistent residual floor
        'tau_eff', 0.35, ...                                    % paper Table 12 value
        'tau_conn', 0.01, ...                                  % normalized score-mass floor for components
        'tau_cover', 0.35, ...                                  % paper Table 12 value
        'use_cover_gate_for_refresh', true, ...                 % cover gate used
        'plot_figures', false);
    cfg.sfr.ref = struct( ...
        'gamma_AD', 1.0, ...                                   % independent N log(1+N) sample rule
        'max_train_points_S', [], 'max_train_points_B', [], ... % [] = use the derived regional cap
        'lambda_reg', 1e-6, ...                                 % unified regularization value
        'eta_accept', 0.0, 'eta_val', cfg.model.eta0, ...
        'val_N', [100, 100], 'b_val', 600, ...
        'use_center_jitter', true, 'kappa_jit', 1.0, ...        % uniform sampling in selected diagnostic cells
        'decouple_jitter_rng', true, ...                        % keep anchor offsets independent of random directions
        'plot_figures', false, ...
        'adam_opts', struct('eta', 0.7, 'maxit', 30, ...
                            'eps_adam', 1e-8));

    % ---------------- RBE (paper script values) ----------------
    cfg.rbe = struct( ...
        'stage_name', 'ScoreFamily', ...
        'families', {{'tanh','ridge_gauss','sin','radial_gauss','mexican_hat'}}, ...
        'family_repeat_mode', 'exclude_last', ...
        'max_family_rounds', 8, ...                             % paper RBE run value (integral_L2)
        'screen_ratio', 0.30, 'screen_max', 500, ...            % m_scr=min{500,ceil(0.3*m_full)}
        'neuron_add', cfg.model.neuron_add, ...
        'm_block0', cfg.model.neuron_add, ...
        'm_block_min', 200, 'm_block_max', cfg.model.neuron_add, ...
        'm_frac_list', [0.2, 0.4, 0.5, 0.6, 0.7, 0.8, 0.9, 1.0], ...
        'prefix_score_ratio', 0.80, ...                         % theta_prefix
        'tau_stop_score', 0.25, ...                             % tau_stop
        'lambda', 1e-6, ...                                     % paper script does NOT set it -> module default 1e-6
        'delta', 3.0e-3, 'q', 2, 'rho', 0.85, ...
        'tau_cap', 1e-4, 'eta_accept', 0.0, ...
        'kappa_map_max', 1e6, ...                               % paper RBE run value (integral_L2)
        'tol_res', 1e-6, ...
        'tol_improve', 0.1, 'stall_patience', 2, ...
        'stop_when_reject', false, 'rollback_worse_tol', 0.05, ...
        'gamma_AD', 1.0, ...                                    % RBE screening sample rule
        'max_train_points', [], ...                             % [] = ceil(gamma_AD*m_scr*log(1+m_scr))
        'plot_figures', false, ...
        'screen_adam_opts', struct('eta', 0.5, 'maxit', 30, ...
            'eps_adam', 1e-8, 'clip_min', [1; 1], 'clip_max', [500; 500], ...
            'minit', 5, 'grad_tol', 1e-12, 'fd_step_rel', 1e-4, ...
            'verbose', false, 'use_rel_grad', false));

    % ---------------- output ----------------
    cfg.output.results_root = fullfile(root, 'results');
    cfg.output.figures_root = fullfile(root, 'figures');
    cfg.output.run_name = '';   % empty -> fixed results/<problem>, overwritten each run
    cfg.output.save_data    = true;   % save plotting-data snapshots
    cfg.output.make_figs    = true;   % export paper figures (compressed PDF + 300dpi PNG)
    cfg.output.pp           = 100;    % plot/eval grid 101x101 (same as paper script)
    cfg.output.val_N        = [100, 100];
end
