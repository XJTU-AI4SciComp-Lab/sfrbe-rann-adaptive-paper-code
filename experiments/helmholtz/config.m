function cfg = config()
%CONFIG  Multiscale Helmholtz experiment.
%
%   Paper Table 5: initial AD-RaNN tanh 3500 (r~[63,60]), SFR not triggered;
%   RBE adds sin 3400 + ridge_gauss 4000 + tanh 2000 -> 12900 total,
%   Rel.L2 = 2.083e-5.
%   Paper Table 11: N_pde=62500, N_b=800, pre-RBE 3500, m_full=2000, lambda=1e-6.
    root = fileparts(fileparts(fileparts(mfilename('fullpath')))); % project root

    cfg.problem = 'helmholtz';
    cfg.paper.table  = 'tab05_helmholtz';
    cfg.paper.figures = { ...
        'fig11_helmholtz_exact_sol', ...
        'fig11_helmholtz_num_sol', ...
        'fig11_helmholtz_ini_error', ...
        'fig11_helmholtz_rbe_error'};
    cfg.paper.fig_file = struct( ...
        'exact_sol', 'Helmholtz_exact_sol', ...
        'num_sol',   'Helmholtz_num_sol', ...
        'ini_error', 'Helmholtz_INI_error', ...
        'rbe_error', 'Helmholtz_RBE_error');

    % ---------------- randomness ----------------
    cfg.seed = 4;
    cfg.rng_reset_each_stage = true;

    % ---------------- grid / boundary (paper Table 11) ----------------
    cfg.grid.N        = [250, 250];  % N_pde = 62500
    cfg.grid.b_point  = 200;         % N_b = 800

    % ---------------- model ----------------
    cfg.model.family     = 'tanh';
    cfg.model.neuron     = 3500;     % initial features
    cfg.model.neuron_add = 2000;     % RBE m_full (paper Table 11)
    cfg.model.r0         = [60; 60];
    cfg.model.eta0       = 100000;

    % ---------------- solver ----------------
    cfg.solver.GPU = 0;
    cfg.solver.QR  = 1;
    cfg.solver.orth_rel_tol = 1e-10;

    % ---------------- PDAD initial scale training ----------------
    cfg.pdad.n_pde_rtrain    = 3000;
    cfg.pdad.n_bd_rtrain     = 600;
    cfg.pdad.n_neuron_rtrain = 800;
    cfg.pdad.opts = struct( ...
        'family',        'tanh', ...
        'maxit',         40, ...
        'learning_rate', 0.5, ...
        'eta_bc_train',  5.0, ...
        'lambda_ridge',  1e-6, ...
        'clip_min',      [1; 1], ...
        'clip_max',      [500; 500], ...
        'normalize_grad', true, ...
        'verbose',       false, ...
        'print_every',   10);

    % ---------------- SFR (paper Table 12 values) ----------------
    cfg.sfr.cfg = struct( ...
        'diag_N', [200, 200], 'partition_grid', [1, 1], 'SAB_eps', 1e-12, ... % one global SFR region
        'theta_dorfler', 0.50, 'theta_res', 0.5, 'theta_grad', 0.5, 'delta_floor', 1.0e-3, ...
        'tau_eff', 0.35, ...
        'tau_conn', 0.01, ...     % normalized score-mass floor for components
        'tau_cover', 0.35, ...
        'use_cover_gate_for_refresh', true, ...
        'plot_figures', false);
    cfg.sfr.ref = struct( ...
        'gamma_AD', 1.0, 'max_train_points_S', [], 'max_train_points_B', [], ...
        'lambda_reg', 1e-6, ...
        'eta_accept', 0.0, 'eta_val', cfg.model.eta0, ...
        'val_N', [100, 100], 'b_val', 600, ...
        'use_center_jitter', true, 'kappa_jit', 1.0, ... % uniform sampling in selected diagnostic cells
        'plot_figures', false, ...
        'adam_opts', struct('eta', 0.7, 'maxit', 30, ...
                            'eps_adam', 1e-8));

    % ---------------- RBE (legacy Helmholtz values; lambda per paper Table 11) ----------------
    cfg.rbe = struct( ...
        'stage_name', 'ScoreFamily', ...
        'use_disk_basis_cache', false, ... % retain the initial response basis in memory
        'families', {{'tanh','ridge_gauss','sin','radial_gauss','mexican_hat'}}, ...
        'family_repeat_mode', 'exclude_last', ...
        'max_family_rounds', 11, ...
        'screen_ratio', 0.30, 'screen_max', 500, ...
        'neuron_add', cfg.model.neuron_add, ...
        'm_block0', cfg.model.neuron_add, ...
        'm_block_min', 200, 'm_block_max', cfg.model.neuron_add, ...
        'm_frac_list', [0.2, 0.4, 0.5, 0.6, 0.7, 0.8, 0.9, 1.0], ...
        'prefix_score_ratio', 0.80, ...
        'tau_stop_score', 0.25, ...
        'lambda', 1e-6, ...
        'delta', 3.0e-3, 'q', 2, 'rho', 0.85, ...
        'tau_cap', 1e-4, 'eta_accept', 0.0, ...
        'kappa_map_max', 1e6, ...
        'tol_res', 1e-6, ...
        'tol_improve', 0.1, 'stall_patience', 2, ...
        'stop_when_reject', true, 'rollback_worse_tol', 0.05, ...
        'gamma_AD', 1.0, 'max_train_points', [], ...
        'plot_figures', false, ...
        'screen_adam_opts', struct('eta', 0.5, 'maxit', 40, ...
            'eps_adam', 1e-8, 'clip_min', [1; 1], 'clip_max', [500; 500], ...
            'minit', 5, 'grad_tol', 1e-12, 'fd_step_rel', 1e-4, ...
            'verbose', false, 'use_rel_grad', false));

    % ---------------- output ----------------
    cfg.output.results_root = fullfile(root, 'results');
    cfg.output.figures_root = fullfile(root, 'figures');
    cfg.output.run_tag_base = 'helmholtz';
    cfg.output.run_name = '';
    cfg.output.save_data    = true;
    cfg.output.make_figs    = false;  % generate later with plotFromResults
    cfg.output.pp           = 150;
    cfg.output.val_N        = [100, 100];
end
