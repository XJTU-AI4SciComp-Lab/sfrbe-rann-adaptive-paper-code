function cfg = burgers3d_config()
%BURGERS3D_CONFIG Settings for the isolated 3D Burgers (x,y,t) pipeline.

    % ----- problem -----
    % Reference saved run used eps = 0.03 (main_score sets 3e-2); the README
    % says 1e-2, but the actual reference result used 0.03.
    cfg.problem.eps_burgers = 0.03;

    % ----- reference-level settings (reproduces rel_L2 ~ 2.64e-6) -----
    cfg.grid.N = [35,35,35];          % [Nx,Ny,Nt]
    cfg.model.neuron = 3000;
    cfg.model.neuron_add = 1000;
    cfg.model.r0 = [10;10;10];
    cfg.seed = 4;

    % ---------------- nonlinear solver ----------------
    % Use the stabilized fixed-operator Picard path by default.  The legacy
    % Newton path is still available by setting enabled=false in this block.
    cfg.fixed_operator = struct( ...
        'enabled', true, ...
        'sigma', 1, ...
        'omega', 0.7, ...
        'omega_min', 1e-3, ...
        'maxit', 25, ...
        'max_line_search', 10, ...
        'accept_increase', 0.0, ...
        'tol', 1e-7, ...
        'eta_bc', 300, ...
        'eta_ic', 300, ...
        'verbose', true);

    % ----- RBE family enrichment -----
    % max_family_rounds is only an upper bound.  The search can stop earlier
    % when a candidate is rejected or the relative improvement is too small.
    cfg.rbe = struct( ...
        'max_family_rounds', 8, ...
        'family_repeat_mode', 'exclude_last', ...
        'screen_ratio', 0.30, ...
        'screen_max', 500, ...
        'prefix_score_ratio', 0.80, ...
        'tau_stop_score', 0.25, ...
        'tau_cap', 1e-4, ...
        'kappa_map_max', 1e6, ...
        'delta', 3.0e-3, 'q', 2, 'rho', 0.85, ...
        'lambda', 1e-6, ...
        'gamma_AD', 1.0, ...
        'max_train_points', [], ...
        'tol_improve', 0.1, ...
        'stop_when_small_improve', true, ...
        'stop_when_reject', true);

    % Cell-centered diagnostic grid used only by SFR.
    cfg.sfr.diag_N = [70,70,70];
    cfg.sfr.sample_within_cell = true; % weighted cell choice, then uniform point in that cell
    cfg.sfr.theta_dorfler = 0.50;
    cfg.sfr.theta_res = 0.5;
    cfg.sfr.theta_grad = 0.5;
    cfg.sfr.delta_floor = 1.0e-3;
    cfg.sfr.tau_eff = 0.35;
    cfg.sfr.exclude_boundary_layers = 0;
    cfg.sfr.min_region_size = 100;
    cfg.sfr.num_rounds = 1;

    % ----- paper-level settings (N_pde=81356 = 43*43*44) -----
    % cfg.grid.N = [43,43,44];
    % cfg.model.neuron = 3000;
    % cfg.model.neuron_add = 1000;
    % cfg.model.r0 = [18;18;18];
    % cfg.sfr.diag_N = [43,43,44];

    % ----- output -----
    cfg.output.pp = [41,41,41];       % evaluation grid [Nx,Ny,Nt]
    cfg.output.results_root = fullfile(fileparts(fileparts(fileparts(mfilename('fullpath')))), 'results');
    cfg.output.run_name = 'burgers3d_fixed';
    cfg.output.make_figs = false;
    cfg.output.save_dense = true;    % save dense 50x50x50 slices for the cube plot
    cfg.output.dense_N = [50,50,50];
    cfg.output.dense_chunk = 8000;
end
